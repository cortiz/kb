cmd("kb", wait=2.0)
mark("tui")
type_("authrizer")                      # a typo still finds it
mark("typo")
key(CTRL("u"))
key(TAB)                                # type filter
key(TAB)
mark("filter")
key(BTAB); key(BTAB)
type_("5xx")
key(ENTER, 1.2)                         # an entry with variables asks first
mark("form")
key(BS); key(BS)
type_("30", wait=0.8)
