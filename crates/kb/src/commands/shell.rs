//! `kb shell init`, `kb shell install`, `kb shell uninstall` command execution.

use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use clap::{Args, Subcommand};
use kb_core::config::Loaded;
use kb_core::shell::dialects::ShellDialect;
use kb_core::shell::templates::{
    KB_STARTUP_BLOCK_BEGIN, KB_STARTUP_BLOCK_END, generate_shell_init,
};

use crate::output::CliError;
use crate::platform::Platform;

#[derive(Subcommand, Debug, Clone)]
pub enum ShellCommand {
    /// Print shell code that defines the widget, binds the key, and loads completions.
    Init(ShellInitArgs),
    /// Install shell integration into your shell startup configuration file.
    Install(ShellInstallArgs),
    /// Remove shell integration from your shell startup configuration file.
    Uninstall(ShellUninstallArgs),
}

#[derive(Args, Debug, Clone)]
pub struct ShellInitArgs {
    /// Shell dialect (zsh, bash, fish).
    pub shell: String,
}

#[derive(Args, Debug, Clone)]
pub struct ShellInstallArgs {
    /// Skip confirmation prompt.
    #[arg(long, short = 'y')]
    pub yes: bool,

    /// Explicit target shell (auto-detected if omitted).
    #[arg(long)]
    pub shell: Option<String>,
}

#[derive(Args, Debug, Clone)]
pub struct ShellUninstallArgs {
    /// Skip confirmation prompt.
    #[arg(long, short = 'y')]
    pub yes: bool,

    /// Explicit target shell (auto-detected if omitted).
    #[arg(long)]
    pub shell: Option<String>,
}

pub fn run_shell(
    platform: &impl Platform,
    loaded: &Loaded,
    command: &ShellCommand,
) -> Result<ExitCode, CliError> {
    match command {
        ShellCommand::Init(args) => {
            let dialect = ShellDialect::from_str(&args.shell).ok_or_else(|| {
                CliError::new(
                    "shell",
                    format!("unknown shell '{}', supported: zsh, bash, fish", args.shell),
                )
            })?;
            let widget_key = loaded.settings.widget_key();
            let save_key = loaded.settings.widget_save_key();
            let script = generate_shell_init(dialect, widget_key, save_key);
            print!("{script}");
            Ok(ExitCode::SUCCESS)
        }
        ShellCommand::Install(args) => {
            let dialect = if let Some(s) = &args.shell {
                ShellDialect::from_str(s).ok_or_else(|| {
                    CliError::new(
                        "shell",
                        format!("unknown shell '{s}', supported: zsh, bash, fish"),
                    )
                })?
            } else {
                detect_current_shell()
            };

            let home = platform.home_dir().ok_or_else(|| {
                CliError::new("shell", "could not determine user home directory")
            })?;
            let target_file = get_shell_startup_file(dialect, &home);

            let snippet = match dialect {
                ShellDialect::Fish => "kb shell init fish | source\n".to_string(),
                ShellDialect::Zsh => "eval \"$(kb shell init zsh)\"\n".to_string(),
                ShellDialect::Bash => "eval \"$(kb shell init bash)\"\n".to_string(),
            };

            let block_text = format!(
                "{KB_STARTUP_BLOCK_BEGIN}\n# Auto-generated by kb shell install; edits outside this block will be overwritten.\n{snippet}{KB_STARTUP_BLOCK_END}\n"
            );

            if !args.yes {
                print!(
                    "Add kb shell integration to {}? [y/N] ",
                    target_file.display()
                );
                let _ = io::stdout().flush();
                let mut line = String::new();
                let _ = io::stdin().read_line(&mut line);
                if !line.trim().eq_ignore_ascii_case("y") {
                    println!("kb: installation aborted");
                    return Ok(ExitCode::SUCCESS);
                }
            }

            let existing = if target_file.exists() {
                fs::read_to_string(&target_file)
                    .map_err(|e| CliError::new("io", e.to_string()))?
            } else {
                String::new()
            };

            if target_file.exists() && !existing.is_empty() {
                let backup_file = target_file.with_extension(format!(
                    "{}.kb-bak",
                    target_file
                        .extension()
                        .map(|s| s.to_string_lossy().into_owned())
                        .unwrap_or_default()
                ));
                let _ = fs::write(backup_file, &existing);
            }

            let new_content = replace_or_append_block(&existing, &block_text);
            if let Some(parent) = target_file.parent() {
                let _ = fs::create_dir_all(parent);
            }
            fs::write(&target_file, new_content)
                .map_err(|e| CliError::new("io", e.to_string()))?;

            println!(
                "kb: installed shell integration for {} in {}",
                dialect.as_str(),
                target_file.display()
            );
            Ok(ExitCode::SUCCESS)
        }
        ShellCommand::Uninstall(args) => {
            let dialect = if let Some(s) = &args.shell {
                ShellDialect::from_str(s).ok_or_else(|| {
                    CliError::new(
                        "shell",
                        format!("unknown shell '{s}', supported: zsh, bash, fish"),
                    )
                })?
            } else {
                detect_current_shell()
            };

            let home = platform.home_dir().ok_or_else(|| {
                CliError::new("shell", "could not determine user home directory")
            })?;
            let target_file = get_shell_startup_file(dialect, &home);

            if !target_file.exists() {
                println!(
                    "kb: startup file {} does not exist",
                    target_file.display()
                );
                return Ok(ExitCode::SUCCESS);
            }

            let existing = fs::read_to_string(&target_file)
                .map_err(|e| CliError::new("io", e.to_string()))?;

            if !existing.contains(KB_STARTUP_BLOCK_BEGIN) {
                println!(
                    "kb: no shell integration block found in {}",
                    target_file.display()
                );
                return Ok(ExitCode::SUCCESS);
            }

            if !args.yes {
                print!(
                    "Remove kb shell integration from {}? [y/N] ",
                    target_file.display()
                );
                let _ = io::stdout().flush();
                let mut line = String::new();
                let _ = io::stdin().read_line(&mut line);
                if !line.trim().eq_ignore_ascii_case("y") {
                    println!("kb: uninstallation aborted");
                    return Ok(ExitCode::SUCCESS);
                }
            }

            let backup_file = target_file.with_extension(format!(
                "{}.kb-bak",
                target_file
                    .extension()
                    .map(|s| s.to_string_lossy().into_owned())
                    .unwrap_or_default()
            ));
            let _ = fs::write(backup_file, &existing);

            let new_content = remove_block(&existing);
            fs::write(&target_file, new_content)
                .map_err(|e| CliError::new("io", e.to_string()))?;

            println!(
                "kb: uninstalled shell integration from {}",
                target_file.display()
            );
            Ok(ExitCode::SUCCESS)
        }
    }
}

pub fn detect_current_shell() -> ShellDialect {
    if let Ok(sh) = std::env::var("SHELL") {
        if sh.contains("zsh") {
            return ShellDialect::Zsh;
        } else if sh.contains("fish") {
            return ShellDialect::Fish;
        } else if sh.contains("bash") {
            return ShellDialect::Bash;
        }
    }
    if cfg!(target_os = "macos") {
        ShellDialect::Zsh
    } else {
        ShellDialect::Bash
    }
}

pub fn get_shell_startup_file(dialect: ShellDialect, home: &Path) -> PathBuf {
    match dialect {
        ShellDialect::Zsh => home.join(".zshrc"),
        ShellDialect::Bash => {
            let bash_prof = home.join(".bash_profile");
            if cfg!(target_os = "macos") && bash_prof.exists() {
                bash_prof
            } else {
                home.join(".bashrc")
            }
        }
        ShellDialect::Fish => home.join(".config/fish/config.fish"),
    }
}

fn replace_or_append_block(content: &str, new_block: &str) -> String {
    if let (Some(start), Some(end_marker)) = (
        content.find(KB_STARTUP_BLOCK_BEGIN),
        content.find(KB_STARTUP_BLOCK_END),
    ) {
        let end = end_marker + KB_STARTUP_BLOCK_END.len();
        let after_end = if content[end..].starts_with('\n') {
            end + 1
        } else {
            end
        };
        let before = &content[..start];
        let after = &content[after_end..];
        format!("{before}{new_block}{after}")
    } else {
        let mut out = content.to_string();
        if !out.is_empty() && !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(new_block);
        out
    }
}

fn remove_block(content: &str) -> String {
    if let (Some(start), Some(end_marker)) = (
        content.find(KB_STARTUP_BLOCK_BEGIN),
        content.find(KB_STARTUP_BLOCK_END),
    ) {
        let end = end_marker + KB_STARTUP_BLOCK_END.len();
        let after_end = if content[end..].starts_with('\n') {
            end + 1
        } else {
            end
        };
        let before = &content[..start];
        let after = &content[after_end..];
        format!("{before}{after}")
    } else {
        content.to_string()
    }
}

#[derive(Args, Debug, Clone)]
pub struct CompletionsArgs {
    /// Target shell dialect (zsh, bash, fish).
    pub shell: String,
}

pub fn run_completions(
    args: &CompletionsArgs,
    cmd: &mut clap::Command,
) -> Result<ExitCode, CliError> {
    let script = generate_completions(&args.shell, cmd)?;
    print!("{script}");
    Ok(ExitCode::SUCCESS)
}

pub fn generate_completions(
    shell_name: &str,
    cmd: &mut clap::Command,
) -> Result<String, CliError> {
    let dialect = ShellDialect::from_str(shell_name)
        .ok_or_else(|| CliError::new("completions", format!("unsupported shell '{shell_name}'")))?;

    let mut buf = Vec::new();
    let clap_shell = match dialect {
        ShellDialect::Zsh => clap_complete::Shell::Zsh,
        ShellDialect::Bash => clap_complete::Shell::Bash,
        ShellDialect::Fish => clap_complete::Shell::Fish,
    };
    clap_complete::generate(clap_shell, cmd, "kb", &mut buf);
    let base = String::from_utf8_lossy(&buf).into_owned();

    let dynamic = match dialect {
        ShellDialect::Zsh => dynamic_zsh(),
        ShellDialect::Bash => dynamic_bash(),
        ShellDialect::Fish => dynamic_fish(),
    };

    Ok(format!("{base}\n{dynamic}\n"))
}

fn dynamic_zsh() -> &'static str {
r#"
# Dynamic completion overrides for kb
_kb_entries() {
    local -a entries
    local line id title
    while IFS=$'\t' read -r id title; do
        if [[ -n "$id" ]]; then
            entries+=("${id}:${title}")
        fi
    done < <(kb __complete entries 2>/dev/null)
    _describe -t entries 'entry' entries
}

_kb_custom() {
    local prev="${words[CURRENT-1]}"
    local cur="${words[CURRENT]}"

    if [[ "$prev" == "--type" || "$cur" == type:* ]]; then
        local p="${cur#type:}"
        local -a types
        types=($(kb __complete types "$p" 2>/dev/null))
        compadd "${types[@]}"
        return
    elif [[ "$prev" == "--tag" || "$cur" == tag:* ]]; then
        local p="${cur#tag:}"
        local -a tags
        tags=($(kb __complete tags "$p" 2>/dev/null))
        compadd "${tags[@]}"
        return
    elif [[ "$prev" == "--var" ]]; then
        local entry_id=""
        local i
        for (( i=2; i < CURRENT-1; i++ )); do
            if [[ "${words[i]}" != -* ]]; then
                entry_id="${words[i]}"
                break
            fi
        done
        if [[ -n "$entry_id" ]]; then
            if [[ "$cur" == *=* ]]; then
                local var_name="${cur%%=*}"
                local val_prefix="${cur#*=}"
                local -a vals
                vals=($(kb __complete var-values "$entry_id" "$var_name" "$val_prefix" 2>/dev/null))
                compadd -P "${var_name}=" "${vals[@]}"
            else
                local -a vars
                vars=($(kb __complete vars "$entry_id" "$cur" 2>/dev/null))
                compadd -S '' "${vars[@]}"
            fi
            return
        fi
    fi

    local subcmd="${words[2]}"
    if [[ "$CURRENT" -eq 3 && ("$subcmd" == "copy" || "$subcmd" == "use" || "$subcmd" == "show" || "$subcmd" == "edit" || "$subcmd" == "rm" || "$subcmd" == "vars" || "$subcmd" == "actions" || "$subcmd" == "open" || "$subcmd" == "run") ]]; then
        _kb_entries
        return
    fi

    _kb "$@"
}
compdef _kb_custom kb
"#
}

fn dynamic_bash() -> &'static str {
r#"
_kb_custom() {
    local cur prev words cword
    _init_completion || return

    if [[ "$prev" == "--type" || "$cur" == type:* ]]; then
        local p="${cur#type:}"
        COMPREPLY=( $(compgen -W "$(kb __complete types "$p" 2>/dev/null)" -- "$p") )
        return 0
    elif [[ "$prev" == "--tag" || "$cur" == tag:* ]]; then
        local p="${cur#tag:}"
        COMPREPLY=( $(compgen -W "$(kb __complete tags "$p" 2>/dev/null)" -- "$p") )
        return 0
    elif [[ "$prev" == "--var" ]]; then
        local entry_id=""
        local i
        for (( i=1; i < cword; i++ )); do
            if [[ "${words[i]}" != -* && "${words[i]}" != "kb" && "${words[i]}" != "use" && "${words[i]}" != "run" && "${words[i]}" != "copy" ]]; then
                entry_id="${words[i]}"
                break
            fi
        done
        if [[ -n "$entry_id" ]]; then
            if [[ "$cur" == *=* ]]; then
                local var_name="${cur%%=*}"
                local val_prefix="${cur#*=}"
                local vals=$(kb __complete var-values "$entry_id" "$var_name" "$val_prefix" 2>/dev/null)
                COMPREPLY=( $(compgen -P "${var_name}=" -W "$vals" -- "$val_prefix") )
            else
                local vars=$(kb __complete vars "$entry_id" "$cur" 2>/dev/null)
                COMPREPLY=( $(compgen -W "$vars" -- "$cur") )
            fi
            return 0
        fi
    fi

    local subcmd="${words[1]}"
    if [[ "$cword" -eq 2 && ("$subcmd" == "copy" || "$subcmd" == "use" || "$subcmd" == "show" || "$subcmd" == "edit" || "$subcmd" == "rm" || "$subcmd" == "vars" || "$subcmd" == "actions" || "$subcmd" == "open" || "$subcmd" == "run") ]]; then
        local ids=$(kb __complete entries "$cur" 2>/dev/null | cut -f1)
        COMPREPLY=( $(compgen -W "$ids" -- "$cur") )
        return 0
    fi

    _kb "$@"
}
complete -F _kb_custom -o bashdefault -o default kb
"#
}

fn dynamic_fish() -> &'static str {
r#"
# Dynamic completions for fish
complete -c kb -n '__fish_seen_subcommand_from copy use show edit rm vars actions open run' -a '(kb __complete entries (commandline -ct) 2>/dev/null)'
complete -c kb -l type -a '(kb __complete types (commandline -ct) 2>/dev/null)'
complete -c kb -l tag -a '(kb __complete tags (commandline -ct) 2>/dev/null)'
complete -c kb -l var -a '(kb __complete vars (commandline -opc)[2] (commandline -ct) 2>/dev/null)'
"#
}
